export function getCategoryBySlug(slug: string): CategoryConfig | undefined {
  return CATEGORIES.find((c) => c.slug === slug);
}

export function getCategoriesByFamily(family: CategoryFamily): CategoryConfig[] {
  return CATEGORIES.filter((c) => c.family === family);
}

export function getPopularCategories(limit = 8): CategoryConfig[] {
  return CATEGORIES.filter((c) => c.isPopular).slice(0, limit);
}

export function getCategoriesByStatus(status: CategoryStatus): CategoryConfig[] {
  return CATEGORIES.filter((c) => c.status === status);
}

